#!/usr/bin/env python3
"""Generate cores3_font.h: anti-aliased 8-bit alpha glyphs rendered from Roboto (Apache 2.0).

    pip install pillow
    python3 gen_font.py Roboto-Medium.ttf Roboto-Light.ttf > cores3_font.h

Fonts: NAME (Medium 32 px, ASCII + degree), SMALL (Medium 22 px, ASCII + degree),
BIG (Light 112 px, digits / . / - only: the temperature number), UNIT (Medium 40 px,
degree + C). The degree sign is stored at code 0x7F.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ASCII = [chr(c) for c in range(32, 127)] + ["\u00b0"]


def code(ch):
    return 0x7F if ch == "\u00b0" else ord(ch)


def build(name, path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in chars:
        adv = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:
            glyphs.append((code(ch), 0, 0, 0, 0, adv, len(data)))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        glyphs.append((code(ch), w, h, x0, y0, adv, len(data)))
        data.extend(img.tobytes())
    return name, glyphs, data, ascent, ascent + descent


def emit(fonts):
    out = ["// Generated by gen_font.py from Roboto (Apache License 2.0). Do not edit.", "#pragma once", "#include <cstdint>", "namespace cores3 {", ""]
    out.append("struct Glyph { uint8_t code, w, h; int8_t xo; int16_t yo; uint8_t adv; uint32_t off; };")
    out.append("struct Font { const Glyph *g; uint16_t n; const uint8_t *data; int ascent; int height; };")
    for name, glyphs, data, ascent, height in fonts:
        out.append(f"static const uint8_t FONT_{name}_DATA[] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[i : i + 24]) + ",")
        out.append("};")
        out.append(f"static const Glyph FONT_{name}_GLYPHS[] = {{")
        for g in sorted(glyphs):
            out.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(
            f"static const Font FONT_{name} = {{FONT_{name}_GLYPHS, {len(glyphs)}, FONT_{name}_DATA, {ascent}, {height}}};"
        )
        out.append("")
    out.append("}  // namespace cores3")
    return "\n".join(out)


if __name__ == "__main__":
    medium, light = sys.argv[1], sys.argv[2]
    fonts = [
        build("NAME", medium, 32, ASCII),
        build("SMALL", medium, 22, ASCII),
        build("BIG", light, 112, list("0123456789.- ")),
        build("UNIT", medium, 40, ["\u00b0", "C"]),
    ]
    print(emit(fonts))
